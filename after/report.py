"""One-page visual meeting report (self-contained HTML, inline SVG charts)."""
import html
from collections import Counter

from . import config

STATUS_COLOR = {"achieved": "#2f9e44", "partial": "#f08c00", "not_started": "#868e96", "dropped": "#e03131"}


def _bars(counts: dict[str, int], width=420) -> str:
    if not counts:
        return "<p class='muted'>No data</p>"
    top = max(counts.values())
    rows = []
    for i, (label, n) in enumerate(counts.items()):
        w = int((width - 170) * n / top)
        y = i * 30
        rows.append(
            f"<text x='0' y='{y + 17}' class='lbl'>{html.escape(label)}</text>"
            f"<rect x='130' y='{y + 4}' width='{w}' height='18' rx='3' class='bar'/>"
            f"<text x='{136 + w}' y='{y + 17}' class='lbl'>{n}</text>"
        )
    return f"<svg viewBox='0 0 {width} {len(counts) * 30}' width='100%'>{''.join(rows)}</svg>"


def build(meeting: dict) -> str:
    a = meeting["analysis"]
    team = {u["handle"]: u["name"] for u in meeting["team"]}
    esc = html.escape
    tasks_per_owner = Counter(team.get(t["owner"], "Unassigned") for t in meeting["human_tasks"])
    goal_counts = Counter(g["status"] for g in a["goal_progress"])

    goals = "".join(
        f"<li><span class='pill' style='background:{STATUS_COLOR[g['status']]}'>{g['status'].replace('_', ' ')}</span>"
        f" {esc(g['goal'])} <span class='muted'>({esc(team.get(g['owner'], g['owner'] or 'n/a'))})</span></li>"
        for g in a["goal_progress"]
    )
    decisions = "".join(f"<li><b>{esc(d['decision'])}</b> <span class='muted'>{esc(d['rationale'])}</span></li>"
                        for d in a["decisions"])
    tasks = "".join(
        f"<tr><td>{esc(t['title'])}</td><td>{esc(team.get(t['owner'], 'UNASSIGNED'))}</td>"
        f"<td>{esc(t['due_date'] or '—')}</td><td>{esc(t['status'])}</td></tr>"
        for t in meeting["human_tasks"]
    )
    questions = "".join(f"<li>{esc(q)}</li>" for q in a["open_questions"])
    nxt = "".join(f"<li>{esc(g)}</li>" for g in a["next_meeting_goals"])
    achieved = goal_counts.get("achieved", 0)

    page = f"""<!doctype html><html><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>
<title>{esc(meeting['title'])} report</title><style>
:root{{--bg:#fff;--fg:#1f2328;--muted:#656d76;--card:#f6f8fa;--bar:#4c6ef5}}
@media (prefers-color-scheme:dark){{:root{{--bg:#0d1117;--fg:#e6edf3;--muted:#8b949e;--card:#161b22;--bar:#748ffc}}}}
body{{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;max-width:900px;margin:0 auto;padding:24px 16px}}
.grid{{display:grid;grid-template-columns:repeat(auto-fit,minmax(260px,1fr));gap:16px}}
.card{{background:var(--card);border-radius:10px;padding:16px}} h1{{margin:0}} h2{{font-size:16px;margin:0 0 8px}}
.muted{{color:var(--muted)}} .pill{{color:#fff;border-radius:99px;padding:1px 8px;font-size:12px}}
.kpi{{font-size:32px;font-weight:700}} table{{width:100%;border-collapse:collapse}} td,th{{text-align:left;padding:6px;border-bottom:1px solid #8884}}
.lbl{{fill:var(--fg);font-size:12px}} .bar{{fill:var(--bar)}} ul{{padding-left:18px;margin:0}}
</style></head><body>
<h1>{esc(meeting['title'])}</h1><p class='muted'>{esc(meeting['date'])} · generated by the Meeting Agent</p>
<div class='card'><p>{esc(a['summary'])}</p></div><br>
<div class='grid'>
 <div class='card'><h2>Last meeting's goals</h2><div class='kpi'>{achieved}/{len(a['goal_progress'])}</div><span class='muted'>achieved</span></div>
 <div class='card'><h2>New tasks</h2><div class='kpi'>{len(meeting['human_tasks'])}</div><span class='muted'>{tasks_per_owner.get('Unassigned', 0)} unassigned</span></div>
 <div class='card'><h2>Decisions</h2><div class='kpi'>{len(a['decisions'])}</div><span class='muted'>{len(a['open_questions'])} open questions</span></div>
</div><br>
<div class='grid'>
 <div class='card'><h2>Goal progress</h2><ul>{goals}</ul></div>
 <div class='card'><h2>Tasks per person</h2>{_bars(dict(tasks_per_owner))}</div>
</div><br>
<div class='card'><h2>Decisions</h2><ul>{decisions}</ul></div><br>
<div class='card'><h2>Action items</h2><table><tr><th>Task</th><th>Owner</th><th>Due</th><th>Status</th></tr>{tasks}</table></div><br>
<div class='grid'><div class='card'><h2>Open questions</h2><ul>{questions}</ul></div>
<div class='card'><h2>Goals for next meeting</h2><ul>{nxt}</ul></div></div>
</body></html>"""
    path = config.OUTPUT_DIR / "reports" / f"{meeting['id']}.html"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(page)
    return f"/output/reports/{path.name}"
